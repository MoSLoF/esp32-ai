// ---- low-level pixel ops ---------------------------------------------------

static inline void _disp_px(int x, int y, uint16_t c) {
  if (x >= 0 && x < DISP_W && y >= 0 && y < DISP_H)
    _disp_fb[y * DISP_W + x] = c;
}

static void _disp_rect(int x, int y, int w, int h, uint16_t c) {
  for (int dy = 0; dy < h && (y + dy) < DISP_H; dy++)
    for (int dx = 0; dx < w && (x + dx) < DISP_W; dx++)
      _disp_fb[(y + dy) * DISP_W + (x + dx)] = c;
}

static void _disp_char(int cx, int cy, char ch, uint16_t fg, uint16_t bg) {
  int idx = (int)ch - FONT_FIRST;
  if (idx < 0 || idx > (FONT_LAST - FONT_FIRST)) idx = 0;
  const uint8_t *glyph = _FONT_DATA + idx * FONT_H;
  int px = cx * FONT_W, py = cy * FONT_H;
  for (int row = 0; row < FONT_H; row++) {
    uint8_t bits = glyph[row];
    for (int col = 0; col < FONT_W; col++)
      _disp_px(px + col, py + row, (bits & (0x80 >> col)) ? fg : bg);
  }
}

static void _disp_str(int cx, int cy, const char *s, uint16_t fg, uint16_t bg) {
  while (*s && cx < TEXT_COLS) {
    _disp_char(cx, cy, *s, fg, bg);
    cx++; s++;
  }
}

static void _disp_str_pad(int cx, int cy, const char *s, int width,
                            uint16_t fg, uint16_t bg) {
  int i = 0;
  while (*s && i < width && (cx + i) < TEXT_COLS) {
    _disp_char(cx + i, cy, *s, fg, bg);
    i++; s++;
  }
  while (i < width && (cx + i) < TEXT_COLS) {
    _disp_char(cx + i, cy, ' ', fg, bg);
    i++;
  }
}

// ---- zone renderers --------------------------------------------------------

static void _disp_render_top(const char *face, const char *name,
                               int n_peers, int n_bonded, int n_encounters) {
  _disp_rect(0, 0, DISP_W, ZONE_TOP_ROWS * FONT_H, COL_BG);
  char buf[TEXT_COLS + 1];
  _disp_str(1, 0, face, COL_ACCENT, COL_BG);
  int flen = strlen(face);
  _disp_str(2 + flen, 0, name, COL_FG, COL_BG);

  snprintf(buf, sizeof(buf), "peers:%d  bonded:%d  total:%d",
           n_peers, n_bonded, n_encounters);
  _disp_str(1, 1, buf, COL_DIM, COL_BG);

  for (int x = 0; x < TEXT_COLS; x++)
    _disp_char(x, 2, '-', COL_DIM, COL_BG);
}

static void _disp_render_mid() {
  for (int r = 0; r < ZONE_MID_ROWS; r++) {
    int row = ZONE_MID_START + r;
    _disp_str_pad(0, row, _disp_mid[r], TEXT_COLS, COL_FG, COL_BG);
  }
}

static void _disp_render_bot_sep() {
  int row = ZONE_BOT_START;
  for (int x = 0; x < TEXT_COLS; x++)
    _disp_char(x, row, '-', COL_DIM, COL_BG);
  _disp_str(1, row, "[ peers ]", COL_ACCENT, COL_BG);
}

// ---- public API ------------------------------------------------------------

static bool display_begin() {
  _disp_fb = (uint16_t *)heap_caps_malloc(
      (size_t)DISP_W * DISP_H * DISP_BPP, MALLOC_CAP_SPIRAM | MALLOC_CAP_DMA);
  if (!_disp_fb) {
    Serial.println("[display] framebuffer alloc failed");
    return false;
  }
  memset(_disp_fb, 0, (size_t)DISP_W * DISP_H * DISP_BPP);
  for (int r = 0; r < ZONE_MID_ROWS; r++)
    memset(_disp_mid[r], 0, DISP_MID_BUF);

  // MIPI-DSI bus configuration.
  esp_lcd_dsi_bus_handle_t dsi_bus;
  esp_lcd_dsi_bus_config_t bus_cfg = {};
  bus_cfg.bus_id = 0;
  bus_cfg.num_data_lanes = 2;
  bus_cfg.phy_clk_src = MIPI_DSI_PHY_CLK_SRC_DEFAULT;
  bus_cfg.lane_bit_rate_mbps = 500;
  esp_err_t err = esp_lcd_new_dsi_bus(&bus_cfg, &dsi_bus);
  if (err != ESP_OK) {
    Serial.printf("[display] DSI bus init failed: %d\n", err);
    heap_caps_free(_disp_fb); _disp_fb = NULL;
    return false;
  }

  // DCS panel init via command-mode IO (S7: required for real ILI9881C panels).
  esp_lcd_panel_io_handle_t dbi_io = NULL;
  esp_lcd_dbi_io_config_t dbi_cfg = {};
  dbi_cfg.virtual_channel = 0;
  dbi_cfg.lcd_cmd_bits = 8;
  dbi_cfg.lcd_param_bits = 8;
  if (esp_lcd_new_panel_io_dbi(dsi_bus, &dbi_cfg, &dbi_io) == ESP_OK && dbi_io) {
    esp_lcd_panel_io_tx_param(dbi_io, 0x11, NULL, 0); // Sleep Out
    delay(120);
    esp_lcd_panel_io_tx_param(dbi_io, 0x29, NULL, 0); // Display On
    delay(20);
    esp_lcd_panel_io_del(dbi_io);
    Serial.println("[display] DCS init sequence sent");
  }

  // DPI panel (video mode).
  esp_lcd_dpi_panel_config_t dpi_cfg = {};
  dpi_cfg.dpi_clk_src = MIPI_DSI_DPI_CLK_SRC_DEFAULT;
  dpi_cfg.dpi_clock_freq_mhz = 40;
  dpi_cfg.virtual_channel = 0;
  dpi_cfg.pixel_format = LCD_COLOR_PIXEL_FORMAT_RGB565;
  dpi_cfg.video_timing.h_size = DISP_W;
  dpi_cfg.video_timing.v_size = DISP_H;
  dpi_cfg.video_timing.hsync_back_porch = 40;
  dpi_cfg.video_timing.hsync_pulse_width = 4;
  dpi_cfg.video_timing.hsync_front_porch = 40;
  dpi_cfg.video_timing.vsync_back_porch = 16;
  dpi_cfg.video_timing.vsync_pulse_width = 4;
  dpi_cfg.video_timing.vsync_front_porch = 16;
  dpi_cfg.num_fbs = 1;

  err = esp_lcd_new_panel_dpi(dsi_bus, &dpi_cfg, &_disp_panel);
  if (err != ESP_OK) {
    Serial.printf("[display] DPI panel init failed: %d\n", err);
    heap_caps_free(_disp_fb); _disp_fb = NULL;
    return false;
  }
  esp_lcd_panel_init(_disp_panel);

  _disp_ready = true;
  Serial.printf("[display] %dx%d ready (%.1f KB fb)\n",
                DISP_W, DISP_H,
                (float)DISP_W * DISP_H * DISP_BPP / 1024.0f);
  return true;
}

static void display_flush() {
  if (!_disp_ready) return;
  esp_lcd_panel_draw_bitmap(_disp_panel, 0, 0, DISP_W, DISP_H, _disp_fb);
}

static void display_puts(const unsigned char *bytes, int len) {
  if (!_disp_ready) return;
  for (int i = 0; i < len; i++) {
    char c = (char)bytes[i];
    if (c == '\n' || _disp_mid_col >= DISP_MID_BUF - 1) {
      _disp_mid[_disp_mid_row][_disp_mid_col] = '\0';
      _disp_mid_row = (_disp_mid_row + 1) % ZONE_MID_ROWS;
      _disp_mid_col = 0;
      memset(_disp_mid[_disp_mid_row], 0, DISP_MID_BUF);
    } else if (c >= 0x20 && c < 0x7F) {
      _disp_mid[_disp_mid_row][_disp_mid_col++] = c;
    }
  }
  _disp_render_mid();
  display_flush();
}

static void display_clear() {
  if (!_disp_ready) return;
  memset(_disp_fb, 0, (size_t)DISP_W * DISP_H * DISP_BPP);
  for (int r = 0; r < ZONE_MID_ROWS; r++)
    memset(_disp_mid[r], 0, DISP_MID_BUF);
  _disp_mid_row = 0;
  _disp_mid_col = 0;
  display_flush();
}

static void display_persona(const char *face, const char *name,
                              const char *quip) {
  if (!_disp_ready) return;
  _disp_render_top(face, name, 0, 0, 0);
  if (quip) _disp_str(1, ZONE_MID_START, quip, COL_DIM, COL_BG);
  display_flush();
}

// Full status update — called from peer_tick or on demand.
static void display_status(const char *face, const char *name,
                             int n_peers, int n_bonded, int n_encounters) {
  if (!_disp_ready) return;
  _disp_render_top(face, name, n_peers, n_bonded, n_encounters);
  display_flush();
}

// Render a single peer row in the bottom zone.
static void display_peer(int slot, const char *peer_name, const char *status,
                           uint16_t color) {
  if (!_disp_ready || slot < 0 || slot >= (ZONE_BOT_ROWS - 1)) return;
  _disp_render_bot_sep();
  int row = ZONE_BOT_START + 1 + slot;
  char buf[TEXT_COLS + 1];
  snprintf(buf, sizeof(buf), " %-16s %s", peer_name, status);
  _disp_str_pad(0, row, buf, TEXT_COLS, color, COL_BG);
  display_flush();
}

static void display_stats(float tok_per_sec, float ms_per_tok) {
  if (!_disp_ready) return;
  char buf[TEXT_COLS + 1];
  snprintf(buf, sizeof(buf), "%.1f tok/s  (%.0f ms/tok)",
           tok_per_sec, ms_per_tok);
  _disp_str(1, ZONE_BOT_START - 1, buf, COL_WARN, COL_BG);
  display_flush();
}

