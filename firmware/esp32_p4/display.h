// MIPI-DSI framebuffer text display for the ESP32-P4.
//
// Renders persona faces, peer status, and inference output to an attached
// MIPI-DSI panel. Uses the ESP-IDF MIPI-DSI driver with a simple software
// framebuffer — no GPU, just pixel-level glyph rendering into a DMA buffer.
//
// The P4 has a dedicated MIPI-DSI peripheral (DPI mode). This driver targets
// common ILI9881C-based 800x480 panels (Waveshare 4.3" is the reference).
//
// Text is rendered with a built-in 8x16 bitmap font. The display is split
// into three zones:
//   - Top bar:   persona face + name + peer count
//   - Middle:    scrolling inference output (last N lines)
//   - Bottom:    peer status table
//
// All rendering is double-buffered via DMA-capable PSRAM. The display_flush()
// call is non-blocking — it queues the buffer for the next VSYNC.

