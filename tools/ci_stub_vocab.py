"""Write a placeholder firmware/esp32_llm/vocab.h so the sketches compile in CI.

The real vocab.h is generated by src/gen_assets.py from the trained tokenizer and
is gitignored. This stub keeps the same symbols and VOCAB_N (so array sizes and
loop bounds match the real build) but maps every token to an empty string. It
is for compile checks only -- firmware built with it prints nothing.

Refuses to overwrite an existing vocab.h unless --force is given.
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "esp32_llm", "vocab.h")
VOCAB_N = 32768


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    if os.path.exists(OUT) and not args.force:
        print(f"{OUT} exists, leaving it alone (use --force to replace)")
        return 0

    with open(OUT, "w") as f:
        f.write("// CI STUB from tools/ci_stub_vocab.py -- not a real vocab.\n")
        f.write("#ifndef VOCAB_H\n#define VOCAB_H\n")
        f.write(f"#define VOCAB_N {VOCAB_N}\n")
        f.write("static const unsigned char VOCAB_BLOB[1] = {0};\n")
        f.write(f"static const int VOCAB_OFF[{VOCAB_N + 1}] = {{0}};\n")
        f.write("#endif\n")
    print(f"wrote stub {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
