#!/usr/bin/env bash
# Compile every firmware sketch with arduino-cli. Used by CI; runs locally too.
#
# Needs arduino-cli with the esp32:esp32 core and the libraries listed in
# .github/workflows/ci.yml installed. Writes a stub vocab.h if the real one
# (from src/gen_assets.py) is missing, and generates a throwaway PSK and OTA
# signing key for the feature builds -- binaries from this script are for
# compile checking only, never for flashing.
#
# Usage: tools/ci_compile.sh [target ...]   (default: all targets)
# Extra arduino-cli flags (e.g. a ctags path override) via ARDUINO_EXTRA_ARGS.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${CI_WORK_DIR:-$(mktemp -d)}"
mkdir -p "$WORK"

S3_FQBN='esp32:esp32:esp32s3:UploadSpeed=921600,USBMode=hwcdc,CDCOnBoot=cdc,UploadMode=default,CPUFreq=240,FlashMode=qio,FlashSize=16M,PartitionScheme=custom,PSRAM=opi,DebugLevel=info'
# bandwidth_bench has no partitions.csv, so it uses the stock partition scheme.
S3_BENCH_FQBN='esp32:esp32:esp32s3:CPUFreq=240,FlashMode=qio,FlashSize=16M,PSRAM=opi'
P4_FQBN='esp32:esp32:esp32p4:FlashMode=qio,FlashSize=32M,PartitionScheme=custom,PSRAM=enabled'
S3_GENERIC_FQBN='esp32:esp32:esp32s3'
ESP32_GENERIC_FQBN='esp32:esp32:esp32'

python3 "$ROOT/tools/ci_stub_vocab.py"

# Throwaway secrets for the feature builds. A forced -include header carries
# them because arduino-cli splits build flags on spaces, which a PEM contains.
CONFIG="$WORK/ci_secrets.h"
if [ ! -f "$CONFIG" ]; then
  openssl ecparam -genkey -name prime256v1 -noout -out "$WORK/ci_ota.key"
  openssl ec -in "$WORK/ci_ota.key" -pubout -out "$WORK/ci_ota.pub" 2>/dev/null
  {
    echo '// Generated by tools/ci_compile.sh -- throwaway CI values, not for devices.'
    echo '#define CRYPTO_PSK "ci-throwaway-psk-not-for-devices"'
    printf '#define OTA_VERIFY_PUBKEY_PEM "'
    awk '{printf "%s\\n", $0}' "$WORK/ci_ota.pub"
    echo '"'
  } > "$CONFIG"
fi

# Every P4 feature that can build today. ESP-NOW and the features riding on it
# (peer protocol, OTA, mesh) can't link on the P4 under Arduino-ESP32 -- see
# the guard in esp32_p4.ino -- so p4-espnow-guard checks that they fail with
# that guard's message rather than silently building or failing some other way.
P4_ALL_FLAGS="-DUSE_DISPLAY=1 -DUSE_SD=1 -DUSE_CRYPTO=1 -DUSE_COMPANION=1"
P4_ESPNOW_FLAGS="-DUSE_ESPNOW=1 -DUSE_PEER_PROTOCOL=1 -DUSE_OTA=1 -DUSE_MESH=1 -DUSE_CRYPTO=1"

# Message the P4 ESP-NOW guard prints; p4-espnow-guard must fail with it.
ESPNOW_GUARD_MSG='ESP-NOW is unavailable on the ESP32-P4'

# name | sketch dir | fqbn | extra compiler flags | expect (empty = must build)
TARGETS=(
  "s3-llm|firmware/esp32_llm|$S3_FQBN||"
  "s3-bandwidth-bench|firmware/bandwidth_bench|$S3_BENCH_FQBN||"
  "p4-default|firmware/esp32_p4|$P4_FQBN||"
  "p4-all-features|firmware/esp32_p4|$P4_FQBN|-include $CONFIG $P4_ALL_FLAGS|"
  "p4-espnow-guard|firmware/esp32_p4|$P4_FQBN|-include $CONFIG $P4_ESPNOW_FLAGS|$ESPNOW_GUARD_MSG"
  "espnow-sender|firmware/espnow_sender|$S3_GENERIC_FQBN|-include $CONFIG|"
  "lora-bridge|firmware/lora_bridge|$ESP32_GENERIC_FQBN||"
)

want=("$@")
failed=()
for t in "${TARGETS[@]}"; do
  IFS='|' read -r name sketch fqbn flags expect <<< "$t"
  if [ ${#want[@]} -gt 0 ] && [[ ! " ${want[*]} " =~ " $name " ]]; then
    continue
  fi
  log="$WORK/$name.log"
  echo "::group::$name ($sketch)"
  rc=0
  # shellcheck disable=SC2086
  arduino-cli compile \
      --fqbn "$fqbn" \
      --build-property compiler.optimization_flags=-O3 \
      --build-property "compiler.cpp.extra_flags=$flags" \
      --build-path "$WORK/build-$name" \
      --warnings default \
      ${ARDUINO_EXTRA_ARGS:-} \
      "$ROOT/$sketch" > "$log" 2>&1 || rc=$?
  cat "$log"
  echo "::endgroup::"
  if [ -z "$expect" ]; then
    if [ $rc -eq 0 ]; then
      echo "PASS $name"
    else
      echo "::error::$name failed to compile"
      failed+=("$name")
    fi
  elif [ $rc -ne 0 ] && grep -qF "$expect" "$log"; then
    echo "PASS $name (failed as expected: $expect)"
  else
    echo "::error::$name was expected to fail with \"$expect\" (exit $rc)"
    failed+=("$name")
  fi
done

if [ ${#failed[@]} -gt 0 ]; then
  echo "FAILED: ${failed[*]}"
  exit 1
fi
echo "all firmware targets compiled"
